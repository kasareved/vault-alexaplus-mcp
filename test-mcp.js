'use strict';
const assert = require('assert');
const { handle } = require('./mcp-server');
let n = 1;
const rpc = (method, params) => handle({ jsonrpc: '2.0', id: n++, method, params });
const call = (name, args) => rpc('tools/call', { name, arguments: args });
const data = r => JSON.parse(r.result.content[0].text);

assert.strictEqual(rpc('initialize', { protocolVersion: '2025-11-25' }).result.serverInfo.name, 'vaultalexa-plus');
assert.strictEqual(rpc('initialize', {}).result.protocolVersion, '2025-11-25');
assert.strictEqual(handle({ jsonrpc: '2.0', method: 'notifications/initialized' }), null);
assert.strictEqual(rpc('tools/list').result.tools.length, 10);
assert.strictEqual(rpc('resources/list').result.resources.length, 2);
assert.strictEqual(rpc('prompts/list').result.prompts.length, 1);

assert.strictEqual(data(call('validate_purchase_safety', { itemName: 'Mouse', itemPrice: 30, category: 'shopping' })).verdict, 'approved');
assert.strictEqual(data(call('validate_purchase_safety', { itemName: 'Monitor', itemPrice: 500, category: 'electronics' })).verdict, 'caution');
assert.strictEqual(data(call('validate_purchase_safety', { itemName: 'Laptop', itemPrice: 1200, category: 'electronics' })).verdict, 'blocked');
assert.strictEqual(call('validate_purchase_safety', { itemName: 'X', itemPrice: 'free', category: 'shopping' }).result.isError, true);
assert.strictEqual(call('validate_purchase_safety', { itemName: 'X', itemPrice: 5, category: 'nope' }).result.isError, true);
assert.strictEqual(data(call('calculate_opportunity_cost', { itemName: 'TV', itemPrice: 300 })).delayMonths, 2);
assert.strictEqual(data(call('predict_monthly_runway', { projectedSpend: 900 })).risk, 'deficit');
assert.strictEqual(data(call('negotiate_dynamic_discount', { itemName: 'Echo Show', currentPrice: 100 })).newPrice, 92);
assert.strictEqual(data(call('split_shared_expense', { title: 'Groceries', totalAmount: 90 })).share, 30);
assert.strictEqual(data(call('predict_inventory_stockout', { asin: 'B0ECHO001' })).status, 'reorder-now');
assert.strictEqual(data(call('generate_morning_briefing', { role: 'seller' })).role, 'seller');
const before = data(call('get_financial_summary', {})).balance;
call('log_transaction', { title: 'Coffee', amount: 10, category: 'groceries' });
assert.strictEqual(data(call('get_financial_summary', {})).balance, before - 10);
assert.strictEqual(rpc('nope').error.code, -32601);
console.log('All MCP tests passed (10 tools, 2 resources, 1 prompt).');
